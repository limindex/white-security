<?php
class SkillExportError extends RuntimeException {}

/**
 * issues/ 원본에서 스킬 참고 파일(references/)을 만든다. site_only 이슈·묶음은 뺀다.
 * references/<group>/INDEX.md(코드 신호 → 이슈 id) + references/<group>/<id>.md(점검 항목·탐지 규칙)
 * + references/<group>/<id>.code.<lang>.md(언어별 코드 예시, 그 언어로 코드를 쓸 때만 읽는다).
 * 라우팅 표(묶음당 한 줄)는 SKILL.md 의 표시 사이에 build.php 가 끼워 넣는다.
 */
final class SkillExport
{
    /** 플러그인 안 스킬 폴더(저장소 루트 기준). 사용자에게 설치되는 것은 plugins/white-security/ 아래뿐이다. */
    public const SKILL_DIR = 'plugins/white-security/skills/white-security';

    /**
     * 스킬 파일에 들어가는 고정 문구를 모두 여기 둔다. 지시문은 영어, 보고·설명 라벨은 한국어(사용자 결정 11-18).
     * 언어를 바꿀 때는 이 표만 고친다.
     */
    public const TEXT = [
        'header' => '<!-- generated from white-security issues; do not edit -->',
        'severity' => '기본 심각도: %s',
        'maps' => '기준: %s',
        'bad_mark' => ' (vulnerable example — do not use)',
        'good_mark' => ' (safe example)',
        'index_title' => '# %s · %s',
        'index_when' => 'When: %s',
        'index_when_default' => '「%s」 상황에서 코드를 쓰거나 고칠 때',
        'index_how' => 'Signals are candidates, not findings: open the matching `<ID>.md` here (max 2 per task) and decide with its checks (constant or request value?).',
        'routing_head' => "| Open when the code involves | Read |\n|---|---|",
        'code_files' => 'Code examples (read only the file for the stack you are writing): %s',
        'code_title' => '# %s 코드 예시 — %s',
        'index_stacks' => 'Stacks: %s',
    ];
    /** references/ 바로 아래의 손으로 쓰는 파일(빌드가 만들거나 지우지 않음). SKILL.md 가 이 경로들을 안내한다. */
    public const HAND_FILES = ['review.md', 'deps.md', 'advisories.md', 'config.md'];
    /** 묶음 INDEX 하나의 상한(estimateTokens 기준). 넘으면 빌드 실패. */
    public const INDEX_MAX_TOKENS = 600;
    /** INDEX 에 싣는 이슈당 신호 수 상한 */
    public const INDEX_MAX_SIGNALS = 8;
    public const HEADER = self::TEXT['header'] . "\n";
    public const ROUTING_START = '<!-- routing:start (generated by build.php from data/groups.json) -->';
    public const ROUTING_END = '<!-- routing:end -->';
    /**
     * 이슈 파일에 옮기는 절 (이 순서: 판정에 쓰는 탐지 규칙을 먼저, dogfood-01 피드백). 코드 예시는 언어별 파일로 따로 쓴다.
     * 기본 심각도·기준 번호 줄은 점검 직전엔 쓸모가 적어 파일 끝에 둔다.
     */
    private const SECTIONS = ['탐지 규칙', '점검 항목'];
    /** 탐지 규칙 중 스킬 파일에서 빼는 칸(모든 이슈에 같은 줄 → SKILL.md 가 한 번만 안내) */
    private const DROP_FIELDS = ['보고 형식'];
    /** 탐지 규칙에서 떼어 점검 항목 뒤 별도 절로 옮기는 칸 */
    private const MOVED_FIELD = '검토 주의';

    /**
     * 보수적인 토큰 추정: 한글 음절(U+AC00–U+D7A3)은 1개씩, 나머지는 바이트/4(올림). 크기 상한·보고서 측정에 쓰는 유일한 식.
     */
    public static function estimateTokens(string $text): int
    {
        $hangul = preg_match_all('/[\x{AC00}-\x{D7A3}]/u', $text);
        return $hangul + (int)ceil((strlen($text) - 3 * $hangul) / 4);
    }

    /** @return list<array{id:string,name:string,when:?string,route:?string,issues:list<Issue>}> 스킬에 들어가는 묶음(이슈가 있는 것만, groups.json 순서) */
    private static function groups(Repository $repo): array
    {
        $by = $repo->byGroup();
        $out = [];
        foreach ($repo->groups() as $g) {
            if ($g['site_only']) continue;
            $list = array_values(array_filter($by[$g['id']] ?? [], fn(Issue $i) => !$i->siteOnly));
            if (!$list) continue;
            $out[] = ['id' => $g['id'], 'name' => $g['name'], 'when' => $g['when'] ?? null, 'route' => $g['route'] ?? null, 'issues' => $list];
        }
        return $out;
    }

    /** 만들 파일 전부를 메모리에서 만든다(쓰기 전에 실패를 알 수 있게). @return array<string,string> 상대 경로 => 내용 */
    public static function render(Repository $repo): array
    {
        $names = [];
        $items = [];
        foreach ($repo->frameworks() as $fw) {
            $names[$fw['id']] = (string)($fw['short'] ?? $fw['name']);
            foreach ($fw['items'] as $it) $items[$fw['id']][$it['id']] = $it['title_ko'];
        }
        $files = [];
        foreach (self::groups($repo) as $g) {
            if ($g['route'] === null) throw new SkillExportError("data/groups.json: `{$g['id']}` 묶음에 route(라우팅 표에 쓰는 영문 코드 신호 키워드 한 줄)가 없습니다");
            $index = self::index($g);
            $tokens = self::estimateTokens($index);
            if ($tokens > self::INDEX_MAX_TOKENS) throw new SkillExportError("{$g['id']}/INDEX.md 가 약 {$tokens}토큰으로 상한 " . self::INDEX_MAX_TOKENS . '토큰을 넘습니다(묶음을 나누거나 when·제목·신호를 줄여야 합니다)');
            $files[$g['id'] . '/INDEX.md'] = $index;
            foreach ($g['issues'] as $i) {
                $code = self::codeFiles($i);
                $files[$g['id'] . '/' . $i->id . '.md'] = self::issueFile($i, $names, $items, array_keys($code));
                foreach ($code as $name => $text) $files[$g['id'] . '/' . $name] = $text;
            }
        }
        ksort($files);
        return $files;
    }

    /** @return list<string> 쓴 파일(상대 경로, 정렬됨) */
    public static function write(Repository $repo, string $dir, ?array $files = null): array
    {
        $dir = rtrim($dir, '/');
        $files ??= self::render($repo);
        foreach ($files as $rel => $text) {
            $path = $dir . '/' . $rel;
            if (!is_dir(dirname($path))) mkdir(dirname($path), 0755, true);
            file_put_contents($path, $text);
        }
        self::prune($dir, $files);
        return array_keys($files);
    }

    /** SKILL.md 에 넣을 라우팅 표(표시 포함). */
    public static function routing(Repository $repo): string
    {
        $rows = [];
        foreach (self::groups($repo) as $g) {
            if ($g['route'] === null) throw new SkillExportError("data/groups.json: `{$g['id']}` 묶음에 route 가 없습니다");
            $rows[] = '| ' . str_replace('|', '\\|', $g['route']) . " | `references/{$g['id']}/INDEX.md` |";
        }
        return self::ROUTING_START . "\n" . self::TEXT['routing_head'] . "\n" . implode("\n", $rows) . "\n" . self::ROUTING_END;
    }

    /**
     * SKILL.md 머리말의 한 줄짜리 `description:` 값(항상 로드되는 부분). 없으면 빈 문자열.
     * 따옴표로 감쌌으면 벗긴다. 여러 줄 YAML 블록은 쓰지 않는다(테스트가 한 줄을 요구).
     */
    public static function description(string $skillMd): string
    {
        if (!preg_match('/\A---\n(.*?)\n---\n/s', $skillMd, $fm)) return '';
        if (!preg_match('/^description:[ \t]*(.+)$/m', $fm[1], $m)) return '';
        $v = trim($m[1]);
        if (strlen($v) >= 2 && ($v[0] === '"' || $v[0] === "'") && $v[-1] === $v[0]) $v = substr($v, 1, -1);
        return $v;
    }

    /** SKILL.md 의 두 표시 사이(표시 포함)를 $block 으로 바꾼다. 표시가 없거나 여러 개면 실패. */
    public static function injectRouting(string $skillMd, string $block): string
    {
        $s = substr_count($skillMd, self::ROUTING_START);
        $e = substr_count($skillMd, self::ROUTING_END);
        if ($s !== 1 || $e !== 1) {
            throw new SkillExportError("SKILL.md 의 라우팅 표 표시 개수가 틀립니다: 시작 {$s}개 · 끝 {$e}개 (각각 1개여야 함: " . self::ROUTING_START . ' … ' . self::ROUTING_END . ')');
        }
        $a = strpos($skillMd, self::ROUTING_START);
        $b = strpos($skillMd, self::ROUTING_END);
        if ($b < $a) throw new SkillExportError('SKILL.md 의 라우팅 표 끝 표시가 시작 표시보다 앞에 있습니다');
        return substr($skillMd, 0, $a) . $block . substr($skillMd, $b + strlen(self::ROUTING_END));
    }

    /** 이번에 만들지 않은 생성 파일(머리 주석이 있는 .md)만 지우고, 빈 묶음 폴더를 치운다. */
    private static function prune(string $dir, array $keep): void
    {
        if (!is_dir($dir)) return;
        $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS), RecursiveIteratorIterator::CHILD_FIRST);
        foreach ($it as $f) {
            $rel = substr($f->getPathname(), strlen($dir) + 1);
            if ($f->isLink()) continue;
            if ($f->isDir()) { @rmdir($f->getPathname()); continue; } // 비어 있을 때만 지워진다
            if (strtolower($f->getExtension()) !== 'md' || isset($keep[$rel])) continue;
            $h = fopen($f->getPathname(), 'r');
            $first = $h ? fgets($h) : false;
            if ($h) fclose($h);
            if ($first === self::HEADER) unlink($f->getPathname());
        }
    }

    /** 묶음 INDEX: 이름·when 한 줄씩 + 이슈마다 "코드 신호 → id 제목". 사람용 요약 문장은 넣지 않는다. */
    private static function index(array $g): string
    {
        $when = $g['when'] ?? null;
        if ($when === null || $when === '') $when = sprintf(self::TEXT['index_when_default'], $g['name']);
        $out = self::HEADER . sprintf(self::TEXT['index_title'], $g['id'], $g['name']) . "\n\n"
            . sprintf(self::TEXT['index_when'], $when) . "\n" . self::TEXT['index_how'] . "\n"
            . sprintf(self::TEXT['index_stacks'], implode(' · ', self::stackLabels($g['issues']))) . "\n\n";
        foreach ($g['issues'] as $i) {
            $signals = $i->detection['signals'] ?? [];
            if (!$signals) throw new SkillExportError(basename($i->path) . ': 탐지 규칙 `찾는 곳` 에서 코드 신호를 뽑지 못했습니다');
            $out .= '- ' . implode(' ', array_map([self::class, 'code'], self::topSignals($signals))) . ' → ' . $i->id . ' ' . self::indexTitle($i) . "\n";
        }
        return $out;
    }

    /** 묶음 이슈들이 가진 코드 키의 label (data/stacks.json 순서, 중복 없음). @param list<Issue> $issues @return list<string> */
    private static function stackLabels(array $issues): array
    {
        $used = [];
        foreach ($issues as $i) foreach (array_keys($i->code) as $k) $used[$k] = true;
        $out = [];
        foreach (Stacks::byKey() as $k => $s) if (isset($used[$k])) $out[] = $s['label'];
        return $out;
    }

    /**
     * INDEX 에 싣는 신호: `찾는 곳` 에 적힌 순서대로 앞 INDEX_MAX_SIGNALS 개. 작성자가 핵심 신호를 앞에 둔다(HANDOFF §4).
     * @param list<string> $signals @return list<string>
     */
    public static function topSignals(array $signals): array
    {
        return array_slice($signals, 0, self::INDEX_MAX_SIGNALS);
    }

    /**
     * INDEX 줄 제목: title_en 이 있으면 그것, 없으면 끝의 한국어 괄호 풀이만 뗀 제목(`Hardcoded Secrets (비밀키 노출)` → `Hardcoded Secrets`).
     * 떼고 나서 약어만 남으면(IPI·SSRF) title_en 이 있어야 한다 — 약어만으로는 무슨 이슈인지 모른다.
     */
    private static function indexTitle(Issue $i): string
    {
        if ($i->titleEn !== null) return $i->titleEn;
        $s = trim(preg_replace('/\s*\([^()]*[\x{AC00}-\x{D7A3}][^()]*\)$/u', '', $i->title));
        if ($s === '') return $i->title;
        if (preg_match('/^[A-Za-z0-9]{2,8}$/', $s) && preg_match_all('/[A-Z]/', $s) >= 2) throw new SkillExportError(basename($i->path) . ": 제목이 약어({$s})뿐이라 INDEX 에 쓸 title_en(예: `{$s} (풀어 쓴 영어 이름)`)이 필요합니다");
        return $s;
    }

    /** 코드 파일 이름(`WS-X-001.code.react-native.md`)에서 코드 키 */
    private static function keyOf(string $file): string
    {
        return preg_match('/\.code\.(.+)\.md$/', $file, $m) ? $m[1] : $file;
    }

    /** 인라인 코드로 감싼다(안에 백틱이 있으면 더 긴 백틱으로). */
    private static function code(string $s): string
    {
        preg_match_all('/`+/', $s, $m);
        $n = $m[0] ? max(array_map('strlen', $m[0])) + 1 : 1;
        $fence = str_repeat('`', $n);
        $pad = $n > 1 || str_starts_with($s, '`') || str_ends_with($s, '`') ? ' ' : '';
        return $fence . $pad . $s . $pad . $fence;
    }

    /**
     * @param array<string,string> $names 맵 키 → 기준 이름(short ?? name)
     * @param array<string,array<string,string>> $items 맵 키 → 항목 id → 한국어 이름
     * @param list<string> $codeFiles 같은 폴더의 언어별 코드 예시 파일 이름
     */
    private static function issueFile(Issue $i, array $names, array $items, array $codeFiles): string
    {
        $codes = [];
        foreach ($i->maps as $key => $list) {
            $name = $names[$key] ?? $key;
            $first = strtok($name, ' ');
            foreach ($list as $c) {
                // 번호가 기준 이름의 첫 낱말로 시작하면(CWE-89) 이름을 앞에 붙이지 않는다
                $label = str_starts_with($c, (string)$first) ? $c : "$name $c";
                if (isset($items[$key][$c])) $label .= '(' . $items[$key][$c] . ')';
                $codes[] = $label;
            }
        }
        $out = self::HEADER . "# {$i->id} {$i->title}\n";
        foreach (self::SECTIONS as $h) {
            $body = $i->sections[$h] ?? '';
            if (trim($body) === '') continue;
            if ($h === '탐지 규칙') $body = self::detection($i->detection);
            $out .= "\n## $h\n\n" . $body . "\n";
        }
        $note = $i->detection['fields'][self::MOVED_FIELD] ?? '';
        if ($note !== '') $out .= "\n## " . self::MOVED_FIELD . "\n\n" . $note . "\n";
        if ($codeFiles) $out .= "\n" . sprintf(self::TEXT['code_files'], implode(' · ', array_map(fn($f) => "`$f` (" . Stacks::label(self::keyOf($f)) . ')', $codeFiles))) . "\n";
        $out .= "\n" . sprintf(self::TEXT['severity'], Site::SEVERITY_LABELS[$i->severity] ?? $i->severity) . "\n";
        if ($codes) $out .= sprintf(self::TEXT['maps'], implode(' · ', $codes)) . "\n";
        return $out;
    }

    /**
     * `## 코드 예시` 의 `### <언어>` 소절마다 파일 하나(`<ID>.code.<언어>.md`). 표지에 영문 설명을 붙인다.
     * @return array<string,string> 파일 이름 => 내용 (원본 소절 순서)
     */
    private static function codeFiles(Issue $i): array
    {
        $parts = []; $lang = null; $fence = null;
        foreach (explode("\n", $i->sections['코드 예시'] ?? '') as $line) {
            if ($fence === null && preg_match('/^(`{3,}|~{3,})/', $line, $m)) $fence = $m[1];
            elseif ($fence !== null && preg_match('/^' . preg_quote($fence[0], '/') . '{' . strlen($fence) . ',}\s*$/', $line)) $fence = null;
            elseif ($fence === null && preg_match('/^### +(.+?)\s*$/', $line, $m)) { $lang = $m[1]; $parts[$lang] = []; continue; }
            if ($lang !== null) $parts[$lang][] = $line;
        }
        $out = [];
        foreach ($parts as $lang => $lines) {
            if (!isset(Stacks::byKey()[$lang]) || !preg_match('/^[a-z0-9][a-z0-9-]*$/', $lang)) throw new SkillExportError(basename($i->path) . ": 코드 예시 소제목 `### $lang` 은(는) 파일 이름에 쓸 수 있는 소문자 언어 이름이어야 합니다");
            $out[$i->id . '.code.' . $lang . '.md'] = self::HEADER . sprintf(self::TEXT['code_title'], $i->id, Stacks::label($lang)) . "\n\n" . trim(self::markCode(implode("\n", $lines)), "\n") . "\n";
        }
        return $out;
    }

    /** 검증된 탐지 규칙을 같은 형식으로 다시 쓰되 DROP_FIELDS 칸과 MOVED_FIELD(따로 절로 옮김)는 뺀다. */
    private static function detection(array $d): string
    {
        $lines = ['- **찾는 곳**: ' . $d['where']];
        foreach ($d['checks'] as $n => $c) $lines[] = '- **검사 ' . ($n + 1) . " — {$c['name']}**: 지적할 때: {$c['flag']} / 지적하지 않을 때: {$c['skip']}";
        $grade = [];
        foreach ($d['grade'] as $lv => $t) $grade[] = "$lv: $t";
        $lines[] = '- **등급**: ' . implode(' / ', $grade);
        foreach (Issue::DETECTION_FIELDS as $f) {
            if (isset($d['fields'][$f]) && !in_array($f, self::DROP_FIELDS, true) && $f !== self::MOVED_FIELD) $lines[] = "- **$f**: " . $d['fields'][$f];
        }
        return implode("\n", $lines);
    }

    /** 코드 블록 밖의 ✗/✓ 표지 줄에 영문 설명을 붙인다(코드 블록 안은 그대로). */
    private static function markCode(string $section): string
    {
        $out = []; $fence = null;
        foreach (explode("\n", $section) as $line) {
            if ($fence === null && preg_match('/^(`{3,}|~{3,})/', $line, $m)) $fence = $m[1];
            elseif ($fence !== null && preg_match('/^' . preg_quote($fence[0], '/') . '{' . strlen($fence) . ',}\s*$/', $line)) $fence = null;
            elseif ($fence === null && str_starts_with($line, '✗')) $line = rtrim($line) . self::TEXT['bad_mark'];
            elseif ($fence === null && str_starts_with($line, '✓')) $line = rtrim($line) . self::TEXT['good_mark'];
            $out[] = $line;
        }
        return implode("\n", $out);
    }
}
