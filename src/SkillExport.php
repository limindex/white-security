<?php
class SkillExportError extends RuntimeException {}

/**
 * issues/ 원본에서 스킬 파일을 만든다. site_only 이슈·묶음은 뺀다. 스킬은 둘(11-18 사용자 결정):
 * - 상시 스킬 `white-security`(SKILL_DIR): 파일을 읽지 않는다(허락 창 0). 위험 이슈 요약(rules 표시 사이)을 빌드가 넣는다.
 * - 검토 스킬 `review`(REVIEW_DIR): references/ 를 갖고, 라우팅 표(routing 표시 사이)를 빌드가 넣는다.
 *   references/<group>/INDEX.md(코드 신호 → 이슈 id) + references/<group>/<id>.md(점검 항목·탐지 규칙)
 *   + references/<group>/<id>.code.<lang>.md(언어별 코드 예시, 그 언어로 코드를 쓸 때만 읽는다).
 * 검토 절차 블록은 검토 에이전트 본문에, 문서 링크 규칙은 references/review.md 의 links 표시 사이에 넣는다.
 */
final class SkillExport
{
    /** 상시 스킬 폴더(저장소 루트 기준). 사용자에게 설치되는 것은 plugins/white-security/ 아래뿐이다. */
    public const SKILL_DIR = 'plugins/white-security/skills/white-security';
    /** 검토 스킬 폴더(`/white-security:review`). 규칙 파일(references/)은 여기 한 곳에만 둔다. */
    public const REVIEW_DIR = 'plugins/white-security/skills/review';
    /** 생성 참고 파일 폴더(저장소 루트 기준) */
    public const REF_DIR = self::REVIEW_DIR . '/references';
    /** 문서 사이트의 기본 경로(build.php --base 기본값과 같음). 보고서의 이슈 링크 = origin + 이 경로 + issues/<id> */
    public const SITE_BASE = '/white-security/';

    /**
     * 스킬 파일에 들어가는 고정 문구를 모두 여기 둔다. 지시문은 영어, 보고·설명 라벨은 한국어(사용자 결정 11-18).
     * 언어를 바꿀 때는 이 표만 고친다.
     */
    public const TEXT = [
        'header' => '<!-- generated from white-security issues; do not edit -->',
        'severity' => '기본 심각도: %s',
        'cwe' => ' · %s',
        'bad_mark' => ' (vulnerable example — do not use)',
        'good_mark' => ' (safe example)',
        'index_title' => '# %s · %s',
        'routing_head' => "| Group | Open its INDEX when the code … |\n|---|---|",
        'code_files' => 'Code examples (open only if 고칠 방법 is not enough; your stack only): %s',
        'code_title' => '# %s 코드 예시 — %s',
        'links_plain' => 'Write issue ids as plain text. No links or images anywhere in the report.',
        'links_url' => 'Write each issue id as a link to its guide page: `[WS-INJ-001](%sWS-INJ-001)`. No other links or images anywhere in the report.',
    ];
    /** references/ 바로 아래의 손으로 쓰는 파일(빌드가 만들거나 지우지 않음). SKILL.md 가 이 경로들을 안내한다. */
    public const HAND_FILES = ['review.md', 'deps.md', 'advisories.md', 'config.md'];
    /** 묶음 INDEX 하나의 상한(estimateTokens 기준). 넘으면 빌드 실패. */
    public const INDEX_MAX_TOKENS = 600;
    /**
     * INDEX 에 싣는 이슈당 신호 수: 묶음마다 MAX 부터 줄여 INDEX 가 INDEX_MAX_TOKENS 안에 드는 가장 큰 수(MIN 미만으로는 줄이지 않음,
     * MIN 으로도 넘으면 빌드 실패). 이슈가 많은 묶음만 신호가 줄고, 나머지는 핵심 신호를 더 싣는다.
     */
    public const INDEX_MAX_SIGNALS = 8;
    public const INDEX_MIN_SIGNALS = 4;
    public const HEADER = self::TEXT['header'] . "\n";
    public const ROUTING_START = '<!-- routing:start (generated by build.php from data/groups.json) -->';
    public const ROUTING_END = '<!-- routing:end -->';
    public const REVIEWER_START = '<!-- reviewer:start (generated by build.php from skills/review/SKILL.md, references/review.md and data/groups.json) -->';
    public const REVIEWER_END = '<!-- reviewer:end -->';
    /** 검토 에이전트 파일(저장소 루트 기준) */
    public const AGENT_FILE = 'plugins/white-security/agents/white-security-reviewer.md';
    /** 검토 에이전트에 그대로 옮기는 검토 스킬 SKILL.md 절 */
    public const REVIEWER_SECTIONS = ['Trust and safety rules', 'Grades and report line'];
    public const RULES_START = '<!-- rules:start (generated by build.php from issues/: high-severity issues, always_on or first check item) -->';
    public const RULES_END = '<!-- rules:end -->';
    public const LINKS_START = '<!-- links:start (generated by build.php from data/site.json origin) -->';
    public const LINKS_END = '<!-- links:end -->';
    /** 상시 스킬 SKILL.md 전체(발동 1회에 읽히는 양) 상한. 넘으면 빌드 실패(HANDOFF §5-1). */
    public const ALWAYS_ON_MAX_TOKENS = 5000;
    public const ALWAYS_ON_MAX_LINES = 150;
    /** 상시 요약 한 줄에 싣는 신호 수 */
    public const RULE_SIGNALS = 2;
    /** 라우팅 표 한 줄(route)의 낱말 상한 */
    public const ROUTE_MAX_WORDS = 12;
    /**
     * 이슈 파일에 옮기는 절 (이 순서: 판정에 쓰는 탐지 규칙을 먼저, dogfood-01 피드백). 코드 예시는 언어별 파일로 따로 쓴다.
     * 기본 심각도(+CWE 번호) 줄은 점검 직전엔 쓸모가 적어 파일 끝에 둔다. 다른 기준 번호는 사이트에만.
     */
    private const SECTIONS = ['탐지 규칙', '점검 항목'];
    /** 탐지 규칙 중 스킬 파일에서 빼는 칸(모든 이슈에 같은 줄 → SKILL.md 가 한 번만 안내) */
    private const DROP_FIELDS = ['보고 형식'];
    /** 탐지 규칙에서 떼어 점검 항목 뒤 별도 절로 옮기는 칸 */
    private const MOVED_FIELD = '검토 주의';

    /**
     * 보수적인 토큰 추정: 한글 음절(U+AC00–U+D7A3)은 1개씩, 나머지는 바이트/4(올림). 크기 상한·보고서 측정에 쓰는 유일한 식.
     */
    public static function estimateTokens(string $text): int
    {
        $hangul = preg_match_all('/[\x{AC00}-\x{D7A3}]/u', $text);
        return $hangul + (int)ceil((strlen($text) - 3 * $hangul) / 4);
    }

    /** @return list<array{id:string,name:string,when:?string,route:?string,issues:list<Issue>}> 스킬에 들어가는 묶음(이슈가 있는 것만, groups.json 순서) */
    private static function groups(Repository $repo): array
    {
        $by = $repo->byGroup();
        $out = [];
        foreach ($repo->groups() as $g) {
            if ($g['site_only']) continue;
            $list = array_values(array_filter($by[$g['id']] ?? [], fn(Issue $i) => !$i->siteOnly));
            if (!$list) continue;
            $out[] = ['id' => $g['id'], 'name' => $g['name'], 'when' => $g['when'] ?? null, 'route' => $g['route'] ?? null, 'issues' => $list];
        }
        return $out;
    }

    /** 만들 파일 전부를 메모리에서 만든다(쓰기 전에 실패를 알 수 있게). @return array<string,string> 상대 경로 => 내용 */
    public static function render(Repository $repo): array
    {
        $files = [];
        foreach (self::groups($repo) as $g) {
            if ($g['route'] === null) throw new SkillExportError("data/groups.json: `{$g['id']}` 묶음에 route(라우팅 표에 쓰는 영문 목적 문구 한 줄, 12낱말 이하)가 없습니다");
            for ($n = self::INDEX_MAX_SIGNALS; ; $n--) {
                $index = self::index($g, $n);
                $tokens = self::estimateTokens($index);
                if ($tokens <= self::INDEX_MAX_TOKENS || $n <= self::INDEX_MIN_SIGNALS) break;
            }
            if ($tokens > self::INDEX_MAX_TOKENS) throw new SkillExportError("{$g['id']}/INDEX.md 가 약 {$tokens}토큰으로 상한 " . self::INDEX_MAX_TOKENS . '토큰을 넘습니다(이슈당 신호 ' . self::INDEX_MIN_SIGNALS . '개로 줄여도 넘음: 묶음을 나누거나 grade_hint 를 줄여야 합니다)');
            $files[$g['id'] . '/INDEX.md'] = $index;
            foreach ($g['issues'] as $i) {
                $code = self::codeFiles($i);
                $files[$g['id'] . '/' . $i->id . '.md'] = self::issueFile($i, array_keys($code));
                foreach ($code as $name => $text) $files[$g['id'] . '/' . $name] = $text;
            }
        }
        ksort($files);
        return $files;
    }

    /** @return list<string> 쓴 파일(상대 경로, 정렬됨) */
    public static function write(Repository $repo, string $dir, ?array $files = null): array
    {
        $dir = rtrim($dir, '/');
        $files ??= self::render($repo);
        foreach ($files as $rel => $text) {
            $path = $dir . '/' . $rel;
            if (!is_dir(dirname($path))) mkdir(dirname($path), 0755, true);
            file_put_contents($path, $text);
        }
        self::prune($dir, $files);
        return array_keys($files);
    }

    /**
     * 라우팅 표(표시 없음): 묶음당 한 줄 `| <group> | <route> |`. route 는 짧은 영문 목적 문구(코드 신호 낱말은 INDEX 에).
     * 낱말 수가 ROUTE_MAX_WORDS 를 넘으면 실패(항상 읽히는 SKILL.md 예산).
     */
    public static function routingTable(Repository $repo): string
    {
        $rows = [];
        foreach (self::groups($repo) as $g) {
            if ($g['route'] === null) throw new SkillExportError("data/groups.json: `{$g['id']}` 묶음에 route 가 없습니다");
            $words = count(preg_split('/\s+/', $g['route']));
            if ($words > self::ROUTE_MAX_WORDS) throw new SkillExportError("data/groups.json: `{$g['id']}` 묶음의 route 가 {$words}낱말로 상한 " . self::ROUTE_MAX_WORDS . '낱말을 넘습니다(목적만 짧게, 코드 신호는 INDEX 에)');
            $rows[] = "| {$g['id']} | " . str_replace('|', '\\|', $g['route']) . ' |';
        }
        return self::TEXT['routing_head'] . "\n" . implode("\n", $rows);
    }

    /** SKILL.md 에 넣을 라우팅 표(표시 포함). */
    public static function routing(Repository $repo): string
    {
        return self::ROUTING_START . "\n" . self::routingTable($repo) . "\n" . self::ROUTING_END;
    }

    /**
     * 검토 에이전트 본문에 넣을 블록(표시 포함): 검토 스킬 SKILL.md 의 신뢰·등급 절 + 라우팅 표 + references/review.md 의 절차(첫 `## ` 부터).
     * 에이전트가 SKILL.md·review.md 를 읽지 않아도 되게 한다(작업 폴더 밖 읽기 권한이 없어도 절차는 갖고 있음).
     */
    public static function reviewerBlock(string $skillMd, string $reviewMd, Repository $repo): string
    {
        $parts = [];
        foreach (self::REVIEWER_SECTIONS as $h) $parts[] = self::section($skillMd, $h, 'SKILL.md');
        $parts[] = "## Routing table\n\n" . self::routingTable($repo);
        $at = strpos($reviewMd, "\n## ");
        if ($at === false) throw new SkillExportError('references/review.md 에 `## ` 절이 없습니다');
        $parts[] = trim(substr($reviewMd, $at + 1));
        return self::REVIEWER_START . "\n" . implode("\n\n", $parts) . "\n" . self::REVIEWER_END;
    }

    /** `## <제목>` 절(다음 `## ` 앞까지, 제목 줄 포함)을 잘라 낸다. 없으면 실패. */
    private static function section(string $md, string $heading, string $file): string
    {
        $pos = strpos($md, "\n## $heading");
        if ($pos === false) throw new SkillExportError("$file 에 `## $heading` 절이 없습니다(검토 에이전트에 넣을 절)");
        $end = strpos($md, "\n## ", $pos + 1);
        return trim($end === false ? substr($md, $pos) : substr($md, $pos, $end - $pos));
    }

    /**
     * SKILL.md 머리말의 한 줄짜리 `description:` 값(항상 로드되는 부분). 없으면 빈 문자열.
     * 따옴표로 감쌌으면 벗긴다. 여러 줄 YAML 블록은 쓰지 않는다(테스트가 한 줄을 요구).
     */
    public static function description(string $skillMd): string
    {
        if (!preg_match('/\A---\n(.*?)\n---\n/s', $skillMd, $fm)) return '';
        if (!preg_match('/^description:[ \t]*(.+)$/m', $fm[1], $m)) return '';
        $v = trim($m[1]);
        if (strlen($v) >= 2 && ($v[0] === '"' || $v[0] === "'") && $v[-1] === $v[0]) $v = substr($v, 1, -1);
        return $v;
    }

    /** SKILL.md 의 두 표시 사이(표시 포함)를 $block 으로 바꾼다. 표시가 없거나 여러 개면 실패. */
    public static function injectRouting(string $skillMd, string $block): string
    {
        return self::inject($skillMd, $block, self::ROUTING_START, self::ROUTING_END, 'SKILL.md 의 라우팅 표');
    }

    /** 상시 SKILL.md 의 요약 표시 사이(표시 포함)를 $block 으로 바꾼다. */
    public static function injectRules(string $skillMd, string $block): string
    {
        return self::inject($skillMd, $block, self::RULES_START, self::RULES_END, '상시 SKILL.md 의 규칙 요약');
    }

    /** references/review.md 의 링크 규칙 표시 사이(표시 포함)를 $block 으로 바꾼다. */
    public static function injectLinks(string $reviewMd, string $block): string
    {
        return self::inject($reviewMd, $block, self::LINKS_START, self::LINKS_END, 'references/review.md 의 링크 규칙');
    }

    /**
     * 보고서 id 링크 규칙(표시 포함). origin(data/site.json, 공개 전엔 빈 값)이 있으면 문서 사이트 이슈 주소로 링크,
     * 없으면 id 만. 어느 쪽이든 그 밖의 링크·이미지는 보고서에 쓰지 않는다(프로젝트 글에서 온 피싱 링크 차단).
     */
    public static function links(string $origin): string
    {
        if ($origin !== '' && !Site::validOrigin($origin)) throw new SkillExportError("data/site.json origin `$origin` 은 https://도메인 형식이어야 합니다");
        $line = $origin === '' ? self::TEXT['links_plain'] : sprintf(self::TEXT['links_url'], self::issueUrlBase($origin));
        return self::LINKS_START . "\n" . $line . "\n" . self::LINKS_END;
    }

    /** 이슈 문서 주소 앞부분(`https://…/white-security/issues/`). origin 이 비면 빈 문자열. */
    public static function issueUrlBase(string $origin): string
    {
        return $origin === '' ? '' : rtrim($origin, '/') . self::SITE_BASE . 'issues/';
    }

    /**
     * 상시 스킬 본문의 규칙 요약(표시 포함): 기본 심각도 high 이슈 한 줄씩 "- <ruleLine> (WS-ID)", 묶음 순서로 이어 쓴다
     * (묶음 제목 줄은 없음 — id 접두어가 묶음을 알려 주고, 발동 1회 예산을 아낀다).
     * 상시 스킬은 이 요약만 보고 안전한 코드를 쓴다(파일 읽기 0).
     */
    public static function rules(Repository $repo): string
    {
        $out = [];
        foreach (self::groups($repo) as $g) {
            foreach ($g['issues'] as $i) {
                if ($i->severity !== 'high' || !$i->detection) continue;
                $out[] = '- ' . self::ruleLine($i) . " ({$i->id})";
            }
        }
        return self::RULES_START . "\n" . implode("\n", $out) . "\n" . self::RULES_END;
    }

    /**
     * 상시 규칙 한 줄(id 제외): 머리말 always_on 이 있으면 그대로(신호와 행동을 작성자가 맞춤),
     * 없으면 앞 신호 RULE_SIGNALS 개 → 점검 항목 첫 문장.
     */
    public static function ruleLine(Issue $i): string
    {
        if ($i->alwaysOn !== null) return $i->alwaysOn;
        $sig = array_slice(self::topSignals($i->detection['signals']), 0, self::RULE_SIGNALS);
        return implode(' ', array_map([self::class, 'code'], $sig)) . ' → ' . self::firstCheck($i);
    }

    /** 점검 항목 첫 줄의 첫 문장. 코드 칸 밖의 괄호(예시·풀이)는 뺀다(코드 칸 속 괄호는 그대로). */
    public static function firstCheck(Issue $i): string
    {
        if (!preg_match('/^- (.+)$/m', $i->sections['점검 항목'] ?? '', $m)) throw new SkillExportError(basename($i->path) . ': 점검 항목 첫 줄을 찾지 못했습니다(상시 스킬 요약에 씀)');
        $spans = [];
        $t = preg_replace_callback('/(`+)(.+?)\1/u', function ($c) use (&$spans) { $spans[] = $c[0]; return "\u{E000}" . (count($spans) - 1) . "\u{E001}"; }, $m[1]);
        do { $t = preg_replace('/\s*\([^()]*\)/u', '', $t, -1, $n); } while ($n > 0);
        if (preg_match('/^(.+?다\.)(?:\s|$)/u', $t, $s)) $t = $s[1];
        return preg_replace_callback('/\x{E000}(\d+)\x{E001}/u', fn($c) => $spans[(int)$c[1]], trim($t));
    }

    /** 상시 SKILL.md 가 예산(토큰·줄)을 넘으면 실패. @return array{tokens:int,lines:int} */
    public static function checkAlwaysOn(string $skillMd): array
    {
        $tokens = self::estimateTokens($skillMd);
        $lines = substr_count($skillMd, "\n");
        if ($tokens > self::ALWAYS_ON_MAX_TOKENS) throw new SkillExportError(self::SKILL_DIR . "/SKILL.md 가 약 {$tokens}토큰으로 상한 " . self::ALWAYS_ON_MAX_TOKENS . '토큰을 넘습니다(본문을 줄이거나 high 이슈 점검 항목 첫 문장을 줄여야 합니다)');
        if ($lines > self::ALWAYS_ON_MAX_LINES) throw new SkillExportError(self::SKILL_DIR . "/SKILL.md 가 {$lines}줄로 상한 " . self::ALWAYS_ON_MAX_LINES . '줄을 넘습니다');
        return ['tokens' => $tokens, 'lines' => $lines];
    }

    /** 검토 에이전트 파일의 두 표시 사이(표시 포함)를 $block 으로 바꾼다. */
    public static function injectReviewer(string $agentMd, string $block): string
    {
        return self::inject($agentMd, $block, self::REVIEWER_START, self::REVIEWER_END, '검토 에이전트(' . self::AGENT_FILE . ')의 절차 블록');
    }

    private static function inject(string $text, string $block, string $start, string $end, string $what): string
    {
        $s = substr_count($text, $start);
        $e = substr_count($text, $end);
        if ($s !== 1 || $e !== 1) {
            throw new SkillExportError("$what 표시 개수가 틀립니다: 시작 {$s}개 · 끝 {$e}개 (각각 1개여야 함: $start … $end)");
        }
        $a = strpos($text, $start);
        $b = strpos($text, $end);
        if ($b < $a) throw new SkillExportError("$what 끝 표시가 시작 표시보다 앞에 있습니다");
        return substr($text, 0, $a) . $block . substr($text, $b + strlen($end));
    }

    /** 이번에 만들지 않은 생성 파일(머리 주석이 있는 .md)만 지우고, 빈 묶음 폴더를 치운다. */
    private static function prune(string $dir, array $keep): void
    {
        if (!is_dir($dir)) return;
        $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS), RecursiveIteratorIterator::CHILD_FIRST);
        foreach ($it as $f) {
            $rel = substr($f->getPathname(), strlen($dir) + 1);
            if ($f->isLink()) continue;
            if ($f->isDir()) { @rmdir($f->getPathname()); continue; } // 비어 있을 때만 지워진다
            if (strtolower($f->getExtension()) !== 'md' || isset($keep[$rel])) continue;
            $h = fopen($f->getPathname(), 'r');
            $first = $h ? fgets($h) : false;
            if ($h) fclose($h);
            if ($first === self::HEADER) unlink($f->getPathname());
        }
    }

    /**
     * 묶음 INDEX: 묶음 이름 + 이슈마다 "코드 신호 → id: 등급 조건". 사람용 요약 문장·이슈 제목·when 은 넣지 않는다
     * (등급 조건이 무슨 이슈인지와 언제 위험인지를 함께 말하고, 묶음 목적은 라우팅 표에 있다. 줄 읽는 법은 review.md 에).
     */
    private static function index(array $g, int $max = self::INDEX_MAX_SIGNALS): string
    {
        $out = self::HEADER . sprintf(self::TEXT['index_title'], $g['id'], $g['name']) . "\n\n";
        foreach ($g['issues'] as $i) {
            $signals = $i->detection['signals'] ?? [];
            if (!$signals) throw new SkillExportError(basename($i->path) . ': 탐지 규칙 `찾는 곳` 에서 코드 신호를 뽑지 못했습니다');
            $out .= '- ' . implode(' ', array_map([self::class, 'code'], self::topSignals($signals, $max))) . ' → ' . $i->id . ': ' . self::gradeHint($i) . "\n";
        }
        return $out;
    }

    /**
     * INDEX 줄 끝의 등급 조건. 조건은 `등급` 칸의 첫 단계(보통 위험) 것: 머리말 grade_hint, 없으면 그 단계 문장의 첫 문장
     * (괄호 풀이·끝 마침표 뺌). 첫 단계가 위험이 아니면 앞에 `주의: ` 처럼 단계 이름을 붙인다.
     */
    public static function gradeHint(Issue $i): string
    {
        $grade = $i->detection['grade'] ?? [];
        if (!$grade) throw new SkillExportError(basename($i->path) . ': 탐지 규칙 `등급` 이 없어 INDEX 등급 조건을 만들 수 없습니다');
        $level = array_key_first($grade);
        $text = $i->gradeHint;
        if ($text === null) {
            $text = preg_split('/\.\s/u', $grade[$level])[0];
            do { $text = preg_replace('/\s*\([^()]*\)/u', '', $text, -1, $n); } while ($n > 0);
        }
        return ($level === '위험' ? '' : $level . ': ') . rtrim(trim($text), '.');
    }

    /**
     * INDEX 에 싣는 신호: `찾는 곳` 에 적힌 순서대로 앞 $max 개. 작성자가 핵심 신호를 앞에 둔다(HANDOFF §4).
     * 앞서 실은 신호를 품은 신호(`yaml.load(` 뒤의 `yaml.load(s)`)는 같은 곳에 걸리므로 건너뛰어, 뒤의 신호가 자리를 얻게 한다.
     * @param list<string> $signals @return list<string>
     */
    public static function topSignals(array $signals, int $max = self::INDEX_MAX_SIGNALS): array
    {
        $out = [];
        foreach ($signals as $s) {
            if (count($out) >= $max) break;
            foreach ($out as $kept) if (str_contains($s, $kept)) continue 2;
            $out[] = $s;
        }
        return $out;
    }

    /** 코드 파일 이름(`WS-X-001.code.react-native.md`)에서 코드 키 */
    private static function keyOf(string $file): string
    {
        return preg_match('/\.code\.(.+)\.md$/', $file, $m) ? $m[1] : $file;
    }

    /** 인라인 코드로 감싼다(안에 백틱이 있으면 더 긴 백틱으로). */
    private static function code(string $s): string
    {
        preg_match_all('/`+/', $s, $m);
        $n = $m[0] ? max(array_map('strlen', $m[0])) + 1 : 1;
        $fence = str_repeat('`', $n);
        $pad = $n > 1 || str_starts_with($s, '`') || str_ends_with($s, '`') ? ' ' : '';
        return $fence . $pad . $s . $pad . $fence;
    }

    /**
     * 기준 번호는 점검 직전엔 쓸모가 적어(상시 발동 예산) CWE 번호만 기본 심각도 줄 끝에 붙인다. 나머지 기준은 사이트에.
     * @param list<string> $codeFiles 같은 폴더의 언어별 코드 예시 파일 이름
     */
    private static function issueFile(Issue $i, array $codeFiles): string
    {
        $cwe = $i->maps['cwe'] ?? [];
        $out = self::HEADER . "# {$i->id} {$i->title}\n";
        foreach (self::SECTIONS as $h) {
            $body = $i->sections[$h] ?? '';
            if (trim($body) === '') continue;
            if ($h === '탐지 규칙') $body = self::detection($i->detection);
            $out .= "\n## $h\n\n" . $body . "\n";
        }
        $note = $i->detection['fields'][self::MOVED_FIELD] ?? '';
        if ($note !== '') $out .= "\n## " . self::MOVED_FIELD . "\n\n" . $note . "\n";
        if ($codeFiles) $out .= "\n" . sprintf(self::TEXT['code_files'], implode(' · ', array_map(fn($f) => "`$f` (" . Stacks::label(self::keyOf($f)) . ')', $codeFiles))) . "\n";
        $out .= "\n" . sprintf(self::TEXT['severity'], Site::SEVERITY_LABELS[$i->severity] ?? $i->severity)
            . ($cwe ? sprintf(self::TEXT['cwe'], implode(' · ', $cwe)) : '') . "\n";
        return $out;
    }

    /**
     * `## 코드 예시` 의 `### <언어>` 소절마다 파일 하나(`<ID>.code.<언어>.md`). 표지에 영문 설명을 붙인다.
     * @return array<string,string> 파일 이름 => 내용 (원본 소절 순서)
     */
    private static function codeFiles(Issue $i): array
    {
        $parts = []; $lang = null; $fence = null;
        foreach (explode("\n", $i->sections['코드 예시'] ?? '') as $line) {
            if ($fence === null && preg_match('/^(`{3,}|~{3,})/', $line, $m)) $fence = $m[1];
            elseif ($fence !== null && preg_match('/^' . preg_quote($fence[0], '/') . '{' . strlen($fence) . ',}\s*$/', $line)) $fence = null;
            elseif ($fence === null && preg_match('/^### +(.+?)\s*$/', $line, $m)) { $lang = $m[1]; $parts[$lang] = []; continue; }
            if ($lang !== null) $parts[$lang][] = $line;
        }
        $out = [];
        foreach ($parts as $lang => $lines) {
            if (!isset(Stacks::byKey()[$lang]) || !preg_match('/^[a-z0-9][a-z0-9-]*$/', $lang)) throw new SkillExportError(basename($i->path) . ": 코드 예시 소제목 `### $lang` 은(는) 파일 이름에 쓸 수 있는 소문자 언어 이름이어야 합니다");
            $out[$i->id . '.code.' . $lang . '.md'] = self::HEADER . sprintf(self::TEXT['code_title'], $i->id, Stacks::label($lang)) . "\n\n" . trim(self::markCode(implode("\n", $lines)), "\n") . "\n";
        }
        return $out;
    }

    /** 검증된 탐지 규칙을 같은 형식으로 다시 쓰되 DROP_FIELDS 칸과 MOVED_FIELD(따로 절로 옮김)는 뺀다. */
    private static function detection(array $d): string
    {
        $lines = ['- **찾는 곳**: ' . $d['where']];
        foreach ($d['checks'] as $n => $c) $lines[] = '- **검사 ' . ($n + 1) . " — {$c['name']}**: 지적할 때: {$c['flag']} / 지적하지 않을 때: {$c['skip']}";
        $grade = [];
        foreach ($d['grade'] as $lv => $t) $grade[] = "$lv: $t";
        $lines[] = '- **등급**: ' . implode(' / ', $grade);
        foreach (Issue::DETECTION_FIELDS as $f) {
            if (isset($d['fields'][$f]) && !in_array($f, self::DROP_FIELDS, true) && $f !== self::MOVED_FIELD) $lines[] = "- **$f**: " . $d['fields'][$f];
        }
        return implode("\n", $lines);
    }

    /** 코드 블록 밖의 ✗/✓ 표지 줄에 영문 설명을 붙인다(코드 블록 안은 그대로). */
    private static function markCode(string $section): string
    {
        $out = []; $fence = null;
        foreach (explode("\n", $section) as $line) {
            if ($fence === null && preg_match('/^(`{3,}|~{3,})/', $line, $m)) $fence = $m[1];
            elseif ($fence !== null && preg_match('/^' . preg_quote($fence[0], '/') . '{' . strlen($fence) . ',}\s*$/', $line)) $fence = null;
            elseif ($fence === null && str_starts_with($line, '✗')) $line = rtrim($line) . self::TEXT['bad_mark'];
            elseif ($fence === null && str_starts_with($line, '✓')) $line = rtrim($line) . self::TEXT['good_mark'];
            $out[] = $line;
        }
        return implode("\n", $out);
    }
}
